# ---------------------------------------------------------------------------
# Standard normal CDF (Phi) — used in power analysis
# ---------------------------------------------------------------------------


def _norm_cdf(x: float) -> float:
    """Standard normal CDF using the complementary error function.

    Phi(x) = 0.5 * erfc(-x / sqrt(2))

    Uses ``math.erfc`` for better numerical precision with extreme values
    — ``math.erf`` returns exactly -1.0 for large negative arguments,
    which would make power exactly 1.0 instead of 1-epsilon.
    """
    return 0.5 * math.erfc(-x / math.sqrt(2.0))


