def _seeded_prng(seed: int):
    """Deterministic LCG PRNG seeded by *seed*.

    Used for deterministic task-cluster bootstrap.  Never uses Python
    ``random``, NumPy RNG, or global state.
    """
    state = seed & ((1 << 63) - 1)
    if state == 0:
        state = 1

    def _next() -> int:
        nonlocal state
        # LCG with constants from Numerical Recipes.
        state = (state * 6364136223846793005 + 1442695040888963407) & ((1 << 63) - 1)
        return state >> 1  # Use upper bits for quality.

    return _next


def task_cluster_bootstrap(
    task_cluster_values: dict[str, list[Fraction]],
    *,
    n_replicates: int = 10_000,
    seed: int = 0,
    n_clusters_per_family: dict[str, int] | None = None,
) -> dict[str, Any]:
    """Deterministic task-cluster bootstrap for the nearest-rank P95.

    Independently resamples complete task clusters within each family
    (with replacement), retaining every checkpoint/repeat record for each
    selected task.  Recomputes the joint nearest-rank P95 for each
    replicate.  Reports the percentile 95% interval of the bootstrap
    distribution.

    ``task_cluster_values`` maps family -> list of per-task joint variation
    statistics (one Fraction per task cluster, each already pooled across
    checkpoints and pairs).

    Does not resample individual probes, seed cells, or pair records.
    """
    if n_replicates <= 0:
        raise ValueError("n_replicates must be positive")

    rng = _seeded_prng(seed)

    families = sorted(task_cluster_values.keys())
    for fam in families:
        vals = task_cluster_values[fam]
        if len(vals) == 0:
            raise ValueError(f"Family '{fam}' has no task cluster values")

    # Collect all pooled values for the point estimate.
    all_vals: list[Fraction] = []
    for fam in families:
        all_vals.extend(task_cluster_values[fam])

    point_estimate = nearest_rank_p95(all_vals)

    # Bootstrap replicates.
    bootstrap_p95s: list[Fraction] = []
    for _ in range(n_replicates):
        rep_vals: list[Fraction] = []
        for fam in families:
            fam_vals = task_cluster_values[fam]
            n_clusters = len(fam_vals)
            for _ in range(n_clusters):
                idx = rng() % n_clusters
                rep_vals.append(fam_vals[idx])
        rep_p95 = nearest_rank_p95(rep_vals)
        bootstrap_p95s.append(
            Fraction(rep_p95["selected_num"], rep_p95["selected_den"])
        )

    # Percentile 95% interval of the bootstrap distribution.
    bootstrap_sorted = sorted(bootstrap_p95s)
    n_boot = len(bootstrap_sorted)
    lo_idx = max(0, math.floor(0.025 * n_boot))
    hi_idx = min(n_boot - 1, math.ceil(0.975 * n_boot) - 1)
    if hi_idx < lo_idx:
        hi_idx = lo_idx

    boot_lo = bootstrap_sorted[lo_idx]
    boot_hi = bootstrap_sorted[hi_idx]

    return {
        "n_replicates": n_replicates,
        "seed": seed,
        "point_estimate_num": point_estimate["selected_num"],
        "point_estimate_den": point_estimate["selected_den"],
        "point_estimate_string": point_estimate["selected_string"],
        "bootstrap_ci_lower_num": boot_lo.numerator,
        "bootstrap_ci_lower_den": boot_lo.denominator,
        "bootstrap_ci_upper_num": boot_hi.numerator,
        "bootstrap_ci_upper_den": boot_hi.denominator,
        "bootstrap_ci_lower_string": canonical_decimal_string(
            boot_lo.numerator, boot_lo.denominator
        ),
        "bootstrap_ci_upper_string": canonical_decimal_string(
            boot_hi.numerator, boot_hi.denominator
        ),
    }


