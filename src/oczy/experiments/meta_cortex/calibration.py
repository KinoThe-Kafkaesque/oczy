def _verify_record_header(
    header: dict[str, Any],
    view: CalibrationViewProtocol,
    *,
    expected_schema: str,
) -> None:
    """Verify that a record file header binds the correct view hashes."""
    schema = header.get("schema")
    if schema != expected_schema:
        raise ValueError(
            f"Record file schema must be {expected_schema!r}, got {schema!r}"
        )
    if header.get("definition_sha256") != view.definition_sha256:
        raise ValueError(
            "Record file definition_sha256 does not match calibration view"
        )
    if header.get("calibration_view_sha256") != view.calibration_view_sha256:
        raise ValueError(
            "Record file calibration_view_sha256 does not match calibration view"
        )
    if header.get("scorer_sha256") != view.scorer_sha256:
        raise ValueError(
            "Record file scorer_sha256 does not match calibration view"
        )


def load_no_update_repeat_records(
    path: Path,
    view: CalibrationViewProtocol,
) -> list[NoUpdateRepeatRecord]:
    """Load and verify no-update repeat records from a canonical JSON file.

    The file must have a header binding definition/calibration-view/scorer
    hashes that match *view*.  Records are deserialized into
    ``NoUpdateRepeatRecord`` objects.
    """
    path = Path(path)
    if not path.is_file():
        raise FileNotFoundError(f"No-update records file not found: {path}")
    data = json.loads(path.read_text(encoding="utf-8"))
    _verify_record_header(data, view, expected_schema=CALIBRATION_RECORDS_SCHEMA)
    raw_records = data.get("records")
    if not isinstance(raw_records, list):
        raise ValueError("No-update records file missing 'records' list")
    return [
        _no_update_repeat_record_from_json(r) for r in raw_records
    ]


