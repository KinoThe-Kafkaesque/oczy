def _canonical_json_compact(obj: Any) -> str:
    """Canonical JSON with sorted keys, compact separators, no NaN."""
    return json.dumps(
        obj,
        allow_nan=False,
        sort_keys=True,
        separators=(",", ":"),
    )


def _hash_json_obj(obj: dict[str, Any], self_hash_field: str = "artifact_sha256") -> str:
    """Compute SHA-256 of canonical JSON excluding the self-hash field."""
    payload = {k: v for k, v in obj.items() if k != self_hash_field}
    json_str = _canonical_json_compact(payload)
    return hashlib.sha256(json_str.encode("utf-8")).hexdigest()


def _write_artifact(path: Path, obj: dict[str, Any], self_hash_field: str) -> str:
    """Write a canonical JSON artifact with self-hash.

    Computes the self-hash (excluding the self-hash field), adds it,
    writes atomically with temp+replace.
    """
    sha = _hash_json_obj(obj, self_hash_field)
    obj[self_hash_field] = sha
    json_str = _canonical_json_compact(obj)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json_str, encoding="utf-8")
    os.replace(tmp, path)
    return sha


