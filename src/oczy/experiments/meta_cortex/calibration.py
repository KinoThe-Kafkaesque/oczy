SCORER_SPEC: dict[str, Any] = {
    "schema": SCORER_SCHEMA,
    "scorer_id": "normalized-exact/v1",
    "normalization": {
        "unicode_normalization": "NFKC",
        "strip": "leading_trailing_unicode_whitespace",
        "preserve": ["case", "punctuation", "internal_whitespace"],
        "reject": ["substring_match", "extra_prose", "token_extraction"],
    },
    "abstain_rule": "abstained when confidence < abstain_threshold; equality scores normally",
    "correct_rule": "correct iff normalized generated bytes equal normalized expected bytes exactly",
    "confidence_definition": "geometric_mean_probability_of_greedily_selected_non_eos_tokens",
    "empty_generation": {"confidence": 0, "abstained": True, "correct": False},
}


def _compute_scorer_sha256() -> str:
    """SHA-256 over canonical scorer spec JSON (matches instrument registry)."""
    return hashlib.sha256(strict_canonical_json(SCORER_SPEC)).hexdigest()


_SCORER_SHA256 = _compute_scorer_sha256()


class FrozenScorer:
    """Frozen normalized-exact response scorer.

    Normalization: NFKC, strip outer whitespace only, preserve
    case/punctuation/internal whitespace.  Matching: exact normalized
    equality — no substring, no prose matching.

    The scorer is deterministic and stateless.  Its SHA-256 covers the
    canonical scorer spec JSON, not Python object repr.
    """

    SCHEMA = SCORER_SCHEMA
    SPEC = SCORER_SPEC

    def normalize_response(self, text: str) -> str:
        """NFKC normalize and strip outer whitespace.

        Preserves case, punctuation, and internal whitespace.
        """
        if not isinstance(text, str):
            raise TypeError("normalize_response requires a str")
        normalized = unicodedata.normalize("NFKC", text)
        return normalized.strip()

    def score_response(self, expected: str, generated: str) -> bool:
        """True iff normalized expected == normalized generated.

        No substring matching — exact normalized equality only.
        """
        norm_expected = self.normalize_response(expected)
        norm_generated = self.normalize_response(generated)
        if not norm_expected:
            return False
        return norm_expected == norm_generated

    def score_battery(
        self,
        expecteds: Sequence[str],
        generateds: Sequence[str],
    ) -> ProbeCount:
        """Score a battery of (expected, generated) pairs.

        Returns ``ProbeCount(correct, total)``.
        """
        if len(expecteds) != len(generateds):
            raise ValueError(
                f"expecteds ({len(expecteds)}) and generateds "
                f"({len(generateds)}) must have equal length"
            )
        total = len(expecteds)
        if total == 0:
            raise ValueError("Battery must be nonempty")
        correct = sum(
            1 for e, g in zip(expecteds, generateds, strict=False)
            if self.score_response(e, g)
        )
        return ProbeCount(correct=correct, total=total)

    @property
    def sha256(self) -> str:
        """SHA-256 over canonical scorer spec."""
        return _SCORER_SHA256


