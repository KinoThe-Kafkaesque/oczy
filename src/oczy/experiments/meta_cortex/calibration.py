def _power_superiority(
    n: int,
    mu_hat: float,
    se_hat: float,
) -> float:
    """Superiority power: pi_sup(n) = 1 - Phi(c_n - mu_hat/se_hat).

    *se_hat* is the standard error of the mean (already s/sqrt(n) or
    a direct SE estimate).  Power increases with n because c_n =
    t_(0.975, n-1) decreases as df grows.
    """
    if n < 2 or se_hat <= 0:
        return 0.0
    c_n = t_critical_975(n - 1)
    z = c_n - mu_hat / se_hat
    return 1.0 - _norm_cdf(z)


def _power_equivalence(
    n: int,
    mu_hat: float,
    s_hat: float,
    delta: float,
) -> float:
    """Equivalence power: pi_eq(n) = Phi((Delta-mu_hat)/se_n - c_n)
    - Phi((-Delta-mu_hat)/se_n + c_n).

    *s_hat* is the standard deviation; se_n = s_hat/sqrt(n).
    """
    if n < 2 or s_hat <= 0 or delta <= 0:
        return 0.0
    se_n = s_hat / math.sqrt(n)
    c_n = t_critical_975(n - 1)
    upper = (delta - mu_hat) / se_n - c_n
    lower = (-delta - mu_hat) / se_n + c_n
    power = _norm_cdf(upper) - _norm_cdf(lower)
    return max(0.0, power)


def compute_power_analysis(
    per_family_endpoint_stats: dict[str, dict[str, dict[str, float]]],
    *,
    equivalence_margin: float,
    target_power: float = 0.80,
    minimum_n: int = 30,
    max_search_n: int = 10_000_000,
) -> dict[str, Any]:
    """Compute per-family/per-endpoint required N and the common sample size.

    For each family and endpoint:
    - Superiority endpoints: power = 1 - Phi(c_n - mu_hat/se_n).
      Acceptance: CI_lower > 0.
    - Equivalence endpoints: power = Phi((Delta-mu_hat)/se_n - c_n)
      - Phi((-Delta-mu_hat)/se_n + c_n).
      Acceptance: CI_lower >= -Delta and CI_upper <= Delta.

    Search integers monotonically from the closed-form normal starting
    estimate until the first n with pi(n) >= target_power.

    Handle zero variance:
    - If s_hat = 0 and superiority mean > 0: required n = minimum_n.
    - If s_hat = 0 and equivalence mean strictly inside margin: required n = minimum_n.
    - If criterion not satisfied: no_finite_n.

    If mu_hat <= 0 for superiority, Delta <= 0, or |mu_hat| >= Delta for
    equivalence: emit no_finite_n.

    Set sample_size = max(minimum_n, all finite required_n).
    """
    families = sorted(per_family_endpoint_stats.keys())
    required_n: dict[str, dict[str, Any]] = {}
    block_reasons: list[str] = []
    all_finite_ns: list[int] = []

    for fam in families:
        endpoints = per_family_endpoint_stats[fam]
        for ep_name in sorted(endpoints.keys()):
            stats = endpoints[ep_name]
            mu_hat = stats["mean"]
            s_hat = stats["sd"]
            is_equivalence = ep_name in EQUIVALENCE_ENDPOINTS

            result: dict[str, Any] = {
                "mean": mu_hat,
                "sd": s_hat,
                "is_equivalence": is_equivalence,
            }

            if is_equivalence:
                delta = equivalence_margin
                result["delta"] = delta

                if delta <= 0:
                    result["required_n"] = None
                    result["status"] = "no_finite_n"
                    result["reason"] = "delta <= 0"
                    result["boundary_power_n_minus_1"] = None
                    result["boundary_power_n"] = None
                    block_reasons.append(
                        f"{fam}/{ep_name}: delta <= 0"
                    )
                    required_n[f"{fam}/{ep_name}"] = result
                    continue

                if abs(mu_hat) >= delta:
                    result["required_n"] = None
                    result["status"] = "no_finite_n"
                    result["reason"] = "|mu_hat| >= delta"
                    result["boundary_power_n_minus_1"] = None
                    result["boundary_power_n"] = None
                    block_reasons.append(
                        f"{fam}/{ep_name}: |mu_hat| >= delta"
                    )
                    required_n[f"{fam}/{ep_name}"] = result
                    continue

                if s_hat == 0:
                    # Zero variance, mean strictly inside margin.
                    result["required_n"] = minimum_n
                    result["status"] = "floor"
                    result["reason"] = "zero_variance_mean_inside_margin"
                    result["boundary_power_n_minus_1"] = None
                    result["boundary_power_n"] = 1.0
                    all_finite_ns.append(minimum_n)
                    required_n[f"{fam}/{ep_name}"] = result
                    continue

                # Search for first n with pi_eq(n) >= target_power.
                # Normal starting estimate.
                # Approximate: solve for n such that (delta - |mu_hat|)/se - c >= Phi_inv(1-power)
                # Use a simple monotonic search from minimum_n.
                found_n = None
                prev_power = 0.0
                for n in range(minimum_n, max_search_n + 1):
                    pwr = _power_equivalence(n, mu_hat, s_hat, delta)
                    if pwr >= target_power:
                        found_n = n
                        result["boundary_power_n"] = pwr
                        if n > minimum_n:
                            result["boundary_power_n_minus_1"] = prev_power
                        else:
                            result["boundary_power_n_minus_1"] = None
                        break
                    prev_power = pwr

                if found_n is None:
                    result["required_n"] = None
                    result["status"] = "no_finite_n"
                    result["reason"] = "power_not_reached_within_search_bound"
                    result["boundary_power_n_minus_1"] = prev_power
                    result["boundary_power_n"] = None
                    block_reasons.append(
                        f"{fam}/{ep_name}: power not reached"
                    )
                else:
                    result["required_n"] = found_n
                    result["status"] = "powered"
                    result["reason"] = None
                    all_finite_ns.append(found_n)

                required_n[f"{fam}/{ep_name}"] = result

            else:
                # Superiority endpoint.
                if mu_hat <= 0:
                    result["required_n"] = None
                    result["status"] = "no_finite_n"
                    result["reason"] = "mu_hat <= 0"
                    result["boundary_power_n_minus_1"] = None
                    result["boundary_power_n"] = None
                    block_reasons.append(
                        f"{fam}/{ep_name}: mu_hat <= 0"
                    )
                    required_n[f"{fam}/{ep_name}"] = result
                    continue

                if s_hat == 0:
                    # Zero variance, mean positive.
                    result["required_n"] = minimum_n
                    result["status"] = "floor"
                    result["reason"] = "zero_variance_mean_positive"
                    result["boundary_power_n_minus_1"] = None
                    result["boundary_power_n"] = 1.0
                    all_finite_ns.append(minimum_n)
                    required_n[f"{fam}/{ep_name}"] = result
                    continue

                # Search for first n with pi_sup(n) >= target_power.
                found_n = None
                prev_power = 0.0
                for n in range(minimum_n, max_search_n + 1):
                    pwr = _power_superiority(n, mu_hat, s_hat / math.sqrt(n))
                    if pwr >= target_power:
                        found_n = n
                        result["boundary_power_n"] = pwr
                        if n > minimum_n:
                            result["boundary_power_n_minus_1"] = prev_power
                        else:
                            result["boundary_power_n_minus_1"] = None
                        break
                    prev_power = pwr

                if found_n is None:
                    result["required_n"] = None
                    result["status"] = "no_finite_n"
                    result["reason"] = "power_not_reached_within_search_bound"
                    result["boundary_power_n_minus_1"] = prev_power
                    result["boundary_power_n"] = None
                    block_reasons.append(
                        f"{fam}/{ep_name}: power not reached"
                    )
                else:
                    result["required_n"] = found_n
                    result["status"] = "powered"
                    result["reason"] = None
                    all_finite_ns.append(found_n)

                required_n[f"{fam}/{ep_name}"] = result

    if block_reasons:
        sample_size = minimum_n  # Will be blocked anyway.
        feasibility = "blocked"
    else:
        sample_size = max(minimum_n, max(all_finite_ns)) if all_finite_ns else minimum_n
        feasibility = "feasible"

    return {
        "required_n_per_endpoint": required_n,
        "sample_size_tasks_per_family": sample_size,
        "feasibility_status": feasibility,
        "block_reasons": tuple(block_reasons),
    }


