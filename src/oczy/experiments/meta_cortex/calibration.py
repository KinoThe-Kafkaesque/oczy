def load_theta_hashes(
    path: Path,
    view: CalibrationViewProtocol,
) -> list[str]:
    """Load and verify developmental theta hashes from a canonical JSON file.

    The file must have a header binding definition/calibration-view/scorer
    hashes that match *view* and contain exactly 5 theta hashes.
    """
    path = Path(path)
    if not path.is_file():
        raise FileNotFoundError(f"Theta hashes file not found: {path}")
    data = json.loads(path.read_text(encoding="utf-8"))
    _verify_record_header(data, view, expected_schema=CALIBRATION_THETA_HASHES_SCHEMA)
    hashes = data.get("theta_hashes")
    if not isinstance(hashes, list):
        raise ValueError("Theta hashes file missing 'theta_hashes' list")
    if len(hashes) != 5:
        raise ValueError(
            f"Expected exactly 5 theta hashes, got {len(hashes)}"
        )
    for h in hashes:
        if not isinstance(h, str) or len(h) != 64:
            raise ValueError("Each theta hash must be 64-char hex")
    return list(hashes)


def normalize_seed_input(raw: bytes | str) -> bytes:
    """Normalize a seed input to exactly 32 raw bytes.

    Accepts either:
    - Exactly 32 raw bytes (returned as-is)
    - 64 lowercase hex characters (decoded to 32 bytes)

    Both forms normalize to the same 32-byte seed.
    """
    if isinstance(raw, str):
        raw = raw.encode("utf-8")
    if len(raw) == 32:
        return raw
    if len(raw) == 64:
        try:
            return bytes.fromhex(raw.decode("ascii"))
        except (ValueError, UnicodeDecodeError) as exc:
            raise ValueError(
                "Seed input of 64 bytes must be lowercase hex characters"
            ) from exc
    raise ValueError(
        f"Seed input must be exactly 32 raw bytes or 64 hex characters, "
        f"got {len(raw)} bytes"
    )


