def run_dev_calibration(
    *,
    view: CalibrationViewProtocol,
    no_update_repeat_records: Sequence[NoUpdateRepeatRecord],
    seed_cell_records: Sequence[SeedCellRecord],
    theta_hashes: Sequence[str],
    organ_hash: str,
    output_dir: Path,
) -> CalibrationResult:
    """Run the complete DEV calibration campaign.

    This function consumes:
    - ``view``: a CalibrationInstrumentView (or compatible protocol) with
      held-back META_VALIDATION calibration rules only.
    - ``no_update_repeat_records``: 20-repeat C1/UPDATE_DISABLED records
      for every calibration task and checkpoint.
    - ``seed_cell_records``: full matched condition matrix for every
      5x5 developmental/evaluation seed cell on calibration rules.
    - ``theta_hashes``: exactly 5 developmental checkpoint theta hashes.
    - ``organ_hash``: the frozen organ hash.

    It produces:
    - ``DEV_DISTRIBUTIONS.json``: complete distribution evidence.
    - ``POWER_ANALYSIS.json``: power analysis and sample size.

    The function never accesses sealed test payload.  ``holdout_accessed``
    is always ``false``.

    The one-step smoke evidence is rejected: if any family has fewer than
    30 calibration tasks, the function raises.
    """
    output_dir = Path(output_dir)

    # --- Validate view ---
    if view.instrument_id != INSTRUMENT_ID:
        raise ValueError(f"instrument_id must be '{INSTRUMENT_ID}'")
    if view.instrument_version != INSTRUMENT_VERSION:
        raise ValueError(f"instrument_version must be '{INSTRUMENT_VERSION}'")
    if len(view.developmental_seeds) != 5:
        raise ValueError("developmental_seeds must have exactly 5 values")
    if len(view.evaluation_seeds) != 5:
        raise ValueError("evaluation_seeds must have exactly 5 values")
    if len(view.no_update_repeat_seeds) != 20:
        raise ValueError("no_update_repeat_seeds must have exactly 20 values")

    # Verify >= 30 calibration tasks per family.
    family_task_counts: dict[str, int] = {}
    for task in view.tasks:
        # Validate META_VALIDATION semantics.
        split = getattr(task, "split", None)
        if split is not DevSplit.META_VALIDATION:
            raise ValueError(
                f"Calibration task has split={split}, expected META_VALIDATION"
            )
        fam = task.family.value if isinstance(task.family, TaskFamily) else str(task.family)
        family_task_counts[fam] = family_task_counts.get(fam, 0) + 1

    for fam, count in family_task_counts.items():
        if count < 30:
            raise ValueError(
                f"Family '{fam}' has only {count} calibration tasks; "
                f"minimum is 30. One-step smoke evidence is rejected."
            )

    # Verify computed counts match the view's declared calibration_tasks_per_family.
    declared_counts = getattr(view, "calibration_tasks_per_family", None)
    if declared_counts is not None:
        for fam, declared in declared_counts.items():
            actual = family_task_counts.get(fam, 0)
            if actual != declared:
                raise ValueError(
                    f"Family '{fam}' has {actual} tasks in view.tasks but "
                    f"calibration_tasks_per_family declares {declared}"
                )

    # Reject one-step smoke: if total tasks < 90 (30*3 families), reject.
    total_tasks = len(view.tasks)
    if total_tasks < 90:
        raise ValueError(
            f"Total calibration tasks ({total_tasks}) < 90 (30 per family * 3 families). "
            f"One-step smoke evidence is rejected as calibration input."
        )

    # --- Validate theta hashes ---
    theta_hashes_tuple = tuple(theta_hashes)
    if len(theta_hashes_tuple) != 5:
        raise ValueError(
            f"Expected exactly 5 theta hashes, got {len(theta_hashes_tuple)}"
        )
    for th in theta_hashes_tuple:
        if not isinstance(th, str) or len(th) != 64:
            raise ValueError("Each theta hash must be 64-char hex")

    # --- Validate no-update repeat records ---
    # Expected: n_tasks * 5 checkpoints * 20 repeats.
    n_tasks = total_tasks
    expected_repeat_records = n_tasks * 5 * 20
    if len(no_update_repeat_records) != expected_repeat_records:
        raise ValueError(
            f"Expected {expected_repeat_records} no-update repeat records "
            f"({n_tasks} tasks * 5 checkpoints * 20 repeats), "
            f"got {len(no_update_repeat_records)}"
        )

    # Verify all repeat records have zero optimizer steps and zero traces.
    for rec in no_update_repeat_records:
        if rec.optimizer_step_count != 0:
            raise ValueError(
                f"Repeat record has optimizer_step_count={rec.optimizer_step_count}, must be 0"
            )
        if rec.trace_count_after != 0:
            raise ValueError(
                f"Repeat record has trace_count_after={rec.trace_count_after}, must be 0"
            )

    # --- Compute joint variation per task/checkpoint ---
    # Group repeat records by (family, rule_fingerprint, developmental_seed_index).
    repeat_groups: dict[tuple[str, str, int], list[NoUpdateRepeatRecord]] = {}
    for rec in no_update_repeat_records:
        key = (rec.family, rec.rule_fingerprint, rec.developmental_seed_index)
        repeat_groups.setdefault(key, []).append(rec)

    # Verify each group has exactly 20 records.
    for key, recs in repeat_groups.items():
        if len(recs) != 20:
            raise ValueError(
                f"Repeat group {key} has {len(recs)} records, expected 20"
            )

    # Compute joint variation stats per task cluster (per task/checkpoint).
    # Then pool across checkpoints for the task-level value.
    task_joint_values: dict[tuple[str, str], list[Fraction]] = {}
    for key, recs in repeat_groups.items():
        family, rule_fp, dev_idx = key
        joint_stats = _compute_joint_variation(recs)
        task_key = (family, rule_fp)
        task_joint_values.setdefault(task_key, []).extend(joint_stats)

    # Pool equally populated v_tdj values across 3 families, 5 checkpoints, 10 pairs.
    # M = 3 * n_cal * 5 * 10, but only 3 * n_cal independent task clusters.
    all_joint_values: list[Fraction] = []
    for _, vals in task_joint_values.items():
        all_joint_values.extend(vals)

    # --- Nearest-rank P95 operative margin ---
    margin_result = nearest_rank_p95(all_joint_values)
    margin_num = margin_result["selected_num"]
    margin_den = margin_result["selected_den"]
    margin_str = margin_result["selected_string"]
    M = margin_result["M"]
    k = margin_result["k"]

    # --- Component diagnostics ---
    # Pool all component diagnostics across tasks/checkpoints.
    all_component_diagnostics: dict[str, list[Fraction]] = {
        "specificity_pair_diff": [],
        "pre_post_diff_even": [],
        "pre_post_diff_odd": [],
    }
    for _, recs in repeat_groups.items():
        comp = _compute_component_diagnostics(recs)
        for comp_name, comp_data in comp.items():
            vals = [
                Fraction(num, den)
                for num, den in zip(comp_data["values_num"], comp_data["values_den"], strict=False)
            ]
            all_component_diagnostics[comp_name].extend(vals)

    component_distributions: dict[str, dict[str, Any]] = {}
    for comp_name, vals in all_component_diagnostics.items():
        p95 = nearest_rank_p95(vals)
        component_distributions[comp_name] = {
            "n": len(vals),
            "p95_num": p95["selected_num"],
            "p95_den": p95["selected_den"],
            "p95_string": p95["selected_string"],
            "M": p95["M"],
            "k": p95["k"],
        }

    # --- Task-cluster bootstrap ---
    # Build per-family lists of per-task joint variation values.
    # Each task cluster contributes one value (the max across its checkpoint/pair values).
    task_cluster_values: dict[str, list[Fraction]] = {}
    for task_key, vals in task_joint_values.items():
        family = task_key[0]
        # One value per task cluster = max of its joint stats.
        task_cluster_values.setdefault(family, []).append(max(vals))

    bootstrap_result = task_cluster_bootstrap(
        task_cluster_values,
        n_replicates=10_000,
        seed=view.task_cluster_bootstrap_seed,
    )

    # --- Unrelated-task summaries ---
    # Cross-task distribution of each rule's seed-averaged C1 specificity accuracy.
    unrelated_task_summaries: dict[str, Any] = {}
    for fam in sorted(family_task_counts.keys()):
        fam_tasks: list[Fraction] = []
        for task_key, _vals in task_joint_values.items():
            if task_key[0] != fam:
                continue
            # Average specificity accuracy across all repeats/checkpoints for this task.
            # We need the original specificity values from the repeat records.
            task_recs = []
            for key, recs in repeat_groups.items():
                if key[0] == fam and key[1] == task_key[1]:
                    task_recs.extend(recs)
            if task_recs:
                avg_spec = sum((r.specificity_accuracy for r in task_recs), Fraction(0)) / len(task_recs)
                fam_tasks.append(avg_spec)
        if fam_tasks:
            ci = task_mean_ci([float(v) for v in fam_tasks])
            unrelated_task_summaries[fam] = {
                "n_tasks": len(fam_tasks),
                "mean": ci["mean"],
                "sd": ci["sd"],
                "ci_lower": ci["ci_lower"],
                "ci_upper": ci["ci_upper"],
            }

    # --- Family distributions ---
    family_distributions: dict[str, dict[str, Any]] = {}
    for fam in sorted(family_task_counts.keys()):
        fam_vals = [
            v for task_key, vals in task_joint_values.items()
            if task_key[0] == fam
            for v in vals
        ]
        p95 = nearest_rank_p95(fam_vals)
        family_distributions[fam] = {
            "n_tasks": family_task_counts[fam],
            "n_values": len(fam_vals),
            "p95_num": p95["selected_num"],
            "p95_den": p95["selected_den"],
            "p95_string": p95["selected_string"],
            "M": p95["M"],
            "k": p95["k"],
        }

    # Pooled distribution.
    pooled_p95 = nearest_rank_p95(all_joint_values)
    pooled_distribution = {
        "n_values": len(all_joint_values),
        "p95_num": pooled_p95["selected_num"],
        "p95_den": pooled_p95["selected_den"],
        "p95_string": pooled_p95["selected_string"],
        "M": pooled_p95["M"],
        "k": pooled_p95["k"],
    }

    # --- Trace audit ---
    trace_audit = {
        "all_fast_zero": all(r.fast_zero for r in no_update_repeat_records),
        "all_slow_zero": all(r.slow_zero for r in no_update_repeat_records),
        "all_optimizer_zero": all(r.optimizer_step_count == 0 for r in no_update_repeat_records),
        "all_trace_zero": all(r.trace_count_after == 0 for r in no_update_repeat_records),
        "n_records_checked": len(no_update_repeat_records),
    }

    # --- Software versions ---
    software_versions = _collect_software_versions()

    # --- Build DEV_DISTRIBUTIONS.json ---
    # Serialize no_update_repeat_records.
    repeat_records_json = tuple(
        rec.to_json_obj() for rec in no_update_repeat_records
    )

    dev_dist_obj: dict[str, Any] = {
        "schema": CALIBRATION_SCHEMA,
        "lifecycle_state": "candidate_unsigned",
        "instrument_id": view.instrument_id,
        "instrument_version": view.instrument_version,
        "definition_sha256": view.definition_sha256,
        "calibration_view_sha256": view.calibration_view_sha256,
        "scorer_sha256": view.scorer_sha256,
        "endpoint_schema_sha256": view.endpoint_schema_sha256,
        "meta_validation_only": True,
        "holdout_accessed": False,
        "developmental_seeds": list(view.developmental_seeds),
        "evaluation_seeds": list(view.evaluation_seeds),
        "no_update_repeat_seeds": list(view.no_update_repeat_seeds),
        "task_cluster_bootstrap_seed": view.task_cluster_bootstrap_seed,
        "seed_derivation_schema": SEED_DERIVATION_SCHEMA,
        "n_calibration_tasks_per_family": dict(family_task_counts),
        "n_developmental_checkpoints": 5,
        "n_no_update_repeats": 20,
        "n_no_update_pairs": 10,
        "no_update_repeat_records": list(repeat_records_json),
        "pairing_formula_id": "non_overlapping_pairs_(0,1),(2,3),...,(18,19)",
        "joint_variation_formula_id": "v_tdj=max(|S_2j-S_2j+1|,|P+_2j-P-_2j|,|P+_2j+1-P-_2j+1|)",
        "component_distributions": component_distributions,
        "family_distributions": family_distributions,
        "pooled_distribution": pooled_distribution,
        "nearest_rank_M": M,
        "nearest_rank_k": k,
        "equivalence_margin": margin_str,
        "equivalence_margin_fraction_num": margin_num,
        "equivalence_margin_fraction_den": margin_den,
        "equivalence_margin_string": margin_str,
        "task_cluster_bootstrap_replicates": 10_000,
        "task_cluster_bootstrap_ci": bootstrap_result,
        "unrelated_task_summaries": unrelated_task_summaries,
        "theta_hashes": list(theta_hashes_tuple),
        "organ_hash": organ_hash,
        "optimizer_step_count": 0,
        "trace_audit": trace_audit,
        "failures": [],
        "software_versions": software_versions,
    }

    dev_dist_path = output_dir / "DEV_DISTRIBUTIONS.json"
    dev_dist_sha = _write_artifact(dev_dist_path, dev_dist_obj, "artifact_sha256")
    dev_dist_bytes = dev_dist_path.read_bytes()
    dev_dist_byte_size = len(dev_dist_bytes)

    # --- Compute task endpoint vectors from seed cell records ---
    # Group seed cell records by (family, rule_fingerprint).
    task_cells: dict[tuple[str, str], list[SeedCellRecord]] = {}
    for scr in seed_cell_records:
        key = (scr.family, scr.rule_fingerprint)
        task_cells.setdefault(key, []).append(scr)

    # Build the set of expected task keys from the view.
    expected_task_keys: set[tuple[str, str]] = set()
    for task in view.tasks:
        fam = task.family.value if isinstance(task.family, TaskFamily) else str(task.family)
        rule_fp = task.rule_fingerprint
        expected_task_keys.add((fam, rule_fp))

    # Verify every view task has seed cell records — no silent skipping.
    for task_key in expected_task_keys:
        if task_key not in task_cells:
            raise ValueError(
                f"Task {task_key} has no seed cell records — "
                f"missing seed cells are not allowed (no complete-case deletion)"
            )

    # For each task, compute the seed-averaged endpoint vector.
    task_endpoint_vectors: dict[tuple[str, str], TaskEndpointVector] = {}
    for task_key, cells in task_cells.items():
        family, rule_fp = task_key
        if task_key not in expected_task_keys:
            raise ValueError(
                f"Seed cell record for task {task_key} not in view.tasks"
            )
        # Verify exactly 25 seed cells (5 dev × 5 eval).
        if len(cells) != 25:
            raise ValueError(
                f"Task {task_key} has {len(cells)} seed cell records, expected 25"
            )
        # Verify all 25 (dev_idx, eval_idx) combinations are present.
        seen_cells: set[tuple[int, int]] = set()
        for cell in cells:
            cell_key = (cell.developmental_seed_index, cell.evaluation_seed_index)
            if cell_key in seen_cells:
                raise ValueError(
                    f"Task {task_key} has duplicate seed cell {cell_key}"
                )
            seen_cells.add(cell_key)
        expected_cells = {(d, e) for d in range(5) for e in range(5)}
        if seen_cells != expected_cells:
            missing = expected_cells - seen_cells
            raise ValueError(
                f"Task {task_key} missing seed cells: {sorted(missing)}"
            )

        # Average endpoints across 25 seed cells.
        all_endpoints: dict[str, list[Fraction]] = {}
        for cell in cells:
            # Build condition map and verify all 6 conditions present.
            cond_map: dict[str, TaskConditionRecord] = {}
            for cr in cell.conditions:
                cond_map[cr.condition] = cr
            ep_vec = compute_endpoint_vector(cond_map)  # raises if missing
            for ep_name, ep_val in ep_vec.items():
                all_endpoints.setdefault(ep_name, []).append(ep_val)

        # Average across seed cells.
        avg_endpoints: dict[str, Fraction] = {}
        for ep_name, vals in all_endpoints.items():
            avg_endpoints[ep_name] = sum(vals, Fraction(0)) / len(vals)

        if len(avg_endpoints) != len(ENDPOINT_NAMES):
            raise ValueError(
                f"Task {task_key} has {len(avg_endpoints)} endpoints, "
                f"expected {len(ENDPOINT_NAMES)}"
            )
        task_endpoint_vectors[task_key] = TaskEndpointVector(
            family=family,
            rule_fingerprint=rule_fp,
            endpoints=avg_endpoints,
        )

    # --- Compute per-family endpoint stats ---
    per_family_endpoint_stats: dict[str, dict[str, dict[str, float]]] = {}
    for fam in sorted(family_task_counts.keys()):
        fam_endpoints: dict[str, list[float]] = {}
        for task_key, tev in task_endpoint_vectors.items():
            if task_key[0] != fam:
                continue
            for ep_name, ep_val in tev.endpoints.items():
                fam_endpoints.setdefault(ep_name, []).append(float(ep_val))

        endpoint_stats: dict[str, dict[str, float]] = {}
        for ep_name in sorted(fam_endpoints.keys()):
            vals = fam_endpoints[ep_name]
            ci = task_mean_ci(vals)
            endpoint_stats[ep_name] = {
                "n": ci["n"],
                "mean": ci["mean"],
                "sd": ci["sd"],
                "ci_lower": ci["ci_lower"],
                "ci_upper": ci["ci_upper"],
                "t_critical": ci["t_critical"],
            }
        per_family_endpoint_stats[fam] = endpoint_stats

    # --- Power analysis ---
    margin_float = float(Fraction(margin_num, margin_den))
    power_result = compute_power_analysis(
        per_family_endpoint_stats,
        equivalence_margin=margin_float,
        target_power=view.target_power,
        minimum_n=view.minimum_tasks_per_family,
    )

    sample_size = power_result["sample_size_tasks_per_family"]
    feasibility = power_result["feasibility_status"]
    block_reasons = power_result["block_reasons"]

    # Build sample_size_by_family (same N for all families).
    sample_size_by_family = {fam: sample_size for fam in sorted(family_task_counts.keys())}
    total_task_count = sample_size * len(sample_size_by_family)

    # --- Build POWER_ANALYSIS.json ---
    power_formulas = {
        "superiority": "pi_sup(n) = 1 - Phi(c_n - mu_hat/se_n)",
        "equivalence": "pi_eq(n) = Phi((Delta-mu_hat)/se_n - c_n) - Phi((-Delta-mu_hat)/se_n + c_n)",
        "se_n": "se_n = s_hat / sqrt(n)",
        "c_n": "c_n = t_(0.975, n-1)",
        "search": "monotonic from minimum_n until first n with pi(n) >= target_power",
    }

    power_obj: dict[str, Any] = {
        "schema": CALIBRATION_SCHEMA,
        "lifecycle_state": "candidate_unsigned",
        "instrument_id": view.instrument_id,
        "instrument_version": view.instrument_version,
        "definition_sha256": view.definition_sha256,
        "calibration_view_sha256": view.calibration_view_sha256,
        "dev_distributions_sha256": dev_dist_sha,
        "dev_distributions_byte_size": dev_dist_byte_size,
        "independent_unit": "independent_task_rule_per_family",
        "estimand": "task_mean_endpoint_delta",
        "endpoint_schema_sha256": view.endpoint_schema_sha256,
        "endpoint_formulas": dict(ENDPOINT_FORMULAS),
        "seed_aggregation_order": "d_tfk = (1/25) * sum_{d=0..4,e=0..4} d_tfdek; family_mean = (1/n_f) * sum_t d_tfk",
        "alpha": 0.05,
        "confidence_level": view.confidence_level,
        "equivalence_semantics": "95%_CI_containment_in_equivalence_interval_one_sided_alpha_0.025_TOST_equivalent",
        "target_power": view.target_power,
        "minimum_tasks_per_family": view.minimum_tasks_per_family,
        "statistical_engine": STATISTICAL_ENGINE,
        "statistical_engine_version": STATISTICAL_ENGINE_VERSION,
        "equivalence_margin": margin_str,
        "equivalence_margin_fraction_num": margin_num,
        "equivalence_margin_fraction_den": margin_den,
        "per_family_endpoint_stats": per_family_endpoint_stats,
        "power_method": "task_normal_planning_approximation_matching_final_CI_rule",
        "power_formulas": power_formulas,
        "required_n_per_endpoint": power_result["required_n_per_endpoint"],
        "diagnostic_family_requirements": {
            fam: {
                ep: power_result["required_n_per_endpoint"].get(f"{fam}/{ep}", {})
                for ep in ENDPOINT_NAMES
            }
            for fam in sorted(family_task_counts.keys())
        },
        "sample_size_tasks_per_family": sample_size,
        "sample_size_by_family": sample_size_by_family,
        "total_task_count": total_task_count,
        "feasibility_status": feasibility,
        "block_reasons": list(block_reasons),
        "holdout_accessed": False,
    }

    power_path = output_dir / "POWER_ANALYSIS.json"
    power_sha = _write_artifact(power_path, power_obj, "artifact_sha256")
    power_bytes = power_path.read_bytes()
    power_byte_size = len(power_bytes)

    return CalibrationResult(
        equivalence_margin=margin_str,
        equivalence_margin_fraction_num=margin_num,
        equivalence_margin_fraction_den=margin_den,
        sample_size_tasks_per_family=sample_size,
        sample_size_by_family=sample_size_by_family,
        feasibility_status=feasibility,
        block_reasons=block_reasons,
        dev_distributions_sha256=dev_dist_sha,
        dev_distributions_byte_size=dev_dist_byte_size,
        power_analysis_sha256=power_sha,
        power_analysis_byte_size=power_byte_size,
        definition_sha256=view.definition_sha256,
        calibration_view_sha256=view.calibration_view_sha256,
        dev_distributions_path=str(dev_dist_path),
        power_analysis_path=str(power_path),
    )


