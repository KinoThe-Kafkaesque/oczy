@dataclass(frozen=True, slots=True)
class ProbeCount:
    """Correct/total for one probe kind in one condition."""

    correct: int
    total: int

    def __post_init__(self) -> None:
        if not isinstance(self.correct, int) or self.correct < 0:
            raise ValueError("ProbeCount.correct must be >= 0")
        if not isinstance(self.total, int) or self.total <= 0:
            raise ValueError("ProbeCount.total must be > 0")
        if self.correct > self.total:
            raise ValueError(
                f"ProbeCount.correct ({self.correct}) > total ({self.total})"
            )

    @property
    def accuracy(self) -> Fraction:
        return Fraction(self.correct, self.total)

    def to_json_obj(self) -> dict[str, int]:
        return {"correct": self.correct, "total": self.total}


@dataclass(frozen=True, slots=True)
class TaskConditionRecord:
    """Complete record for one task under one condition.

    No raw prompt, correction, label, or generated text.
    """

    family: str
    rule_fingerprint: str
    assignment_fingerprint: str
    composition_fingerprint: str
    paraphrase_group_fingerprint: str
    developmental_seed_index: int
    evaluation_seed_index: int
    developmental_seed: int
    evaluation_seed: int
    condition: str
    score_vector_hash: str
    same_rule: ProbeCount
    transfer: ProbeCount
    composition: ProbeCount
    specificity: ProbeCount
    pre_learning_primary: ProbeCount
    immediately_pre_deletion_primary: ProbeCount
    post_deletion_primary: ProbeCount
    theta_hash: str
    organ_hash: str
    state_hash: str
    optimizer_step_count: int
    trace_count_after: int
    fast_zero: bool
    slow_zero: bool

    def __post_init__(self) -> None:
        for fp_name in (
            "rule_fingerprint", "assignment_fingerprint",
            "composition_fingerprint", "paraphrase_group_fingerprint",
            "score_vector_hash", "theta_hash", "organ_hash", "state_hash",
        ):
            fp = getattr(self, fp_name)
            if not isinstance(fp, str) or len(fp) != 64:
                raise ValueError(
                    f"TaskConditionRecord.{fp_name} must be 64-char hex"
                )
        if not (0 <= self.developmental_seed_index < 5):
            raise ValueError("developmental_seed_index must be in [0,5)")
        if not (0 <= self.evaluation_seed_index < 5):
            raise ValueError("evaluation_seed_index must be in [0,5)")
        if not isinstance(self.condition, str) or not self.condition:
            raise ValueError("condition must be non-empty string")
        for pc_name in (
            "same_rule", "transfer", "composition", "specificity",
            "pre_learning_primary", "immediately_pre_deletion_primary",
            "post_deletion_primary",
        ):
            pc = getattr(self, pc_name)
            if not isinstance(pc, ProbeCount):
                raise ValueError(f"{pc_name} must be a ProbeCount")
        if self.optimizer_step_count < 0:
            raise ValueError("optimizer_step_count must be >= 0")
        if self.trace_count_after < 0:
            raise ValueError("trace_count_after must be >= 0")

    @property
    def primary_accuracy(self) -> Fraction:
        """A_primary = pool same_rule + transfer + composition."""
        c = self.same_rule.correct + self.transfer.correct + self.composition.correct
        t = self.same_rule.total + self.transfer.total + self.composition.total
        return Fraction(c, t)

    @property
    def specificity_accuracy(self) -> Fraction:
        return self.specificity.accuracy

    def to_json_obj(self) -> dict[str, Any]:
        return {
            "family": self.family,
            "rule_fingerprint": self.rule_fingerprint,
            "assignment_fingerprint": self.assignment_fingerprint,
            "composition_fingerprint": self.composition_fingerprint,
            "paraphrase_group_fingerprint": self.paraphrase_group_fingerprint,
            "developmental_seed_index": self.developmental_seed_index,
            "evaluation_seed_index": self.evaluation_seed_index,
            "developmental_seed": self.developmental_seed,
            "evaluation_seed": self.evaluation_seed,
            "condition": self.condition,
            "score_vector_hash": self.score_vector_hash,
            "same_rule": self.same_rule.to_json_obj(),
            "transfer": self.transfer.to_json_obj(),
            "composition": self.composition.to_json_obj(),
            "specificity": self.specificity.to_json_obj(),
            "pre_learning_primary": self.pre_learning_primary.to_json_obj(),
            "immediately_pre_deletion_primary": self.immediately_pre_deletion_primary.to_json_obj(),
            "post_deletion_primary": self.post_deletion_primary.to_json_obj(),
            "theta_hash": self.theta_hash,
            "organ_hash": self.organ_hash,
            "state_hash": self.state_hash,
            "optimizer_step_count": self.optimizer_step_count,
            "trace_count_after": self.trace_count_after,
            "fast_zero": self.fast_zero,
            "slow_zero": self.slow_zero,
        }


@dataclass(frozen=True, slots=True)
class SeedCellRecord:
    """One (dev_seed, eval_seed) cell for one task.

    Seed cells are repeated measurements; they never increase inferential n.
    """

    developmental_seed_index: int
    evaluation_seed_index: int
    developmental_seed: int
    evaluation_seed: int
    rule_fingerprint: str
    family: str
    conditions: tuple[TaskConditionRecord, ...]

    def __post_init__(self) -> None:
        if not isinstance(self.conditions, tuple):
            object.__setattr__(self, "conditions", tuple(self.conditions))
        if len(self.conditions) == 0:
            raise ValueError("SeedCellRecord.conditions must be nonempty")
        for cr in self.conditions:
            if not isinstance(cr, TaskConditionRecord):
                raise ValueError("conditions must contain TaskConditionRecord")
        if not isinstance(self.rule_fingerprint, str) or len(self.rule_fingerprint) != 64:
            raise ValueError("rule_fingerprint must be 64-char hex")

    def to_json_obj(self) -> dict[str, Any]:
        return {
            "developmental_seed_index": self.developmental_seed_index,
            "evaluation_seed_index": self.evaluation_seed_index,
            "developmental_seed": self.developmental_seed,
            "evaluation_seed": self.evaluation_seed,
            "rule_fingerprint": self.rule_fingerprint,
            "family": self.family,
            "conditions": [cr.to_json_obj() for cr in self.conditions],
        }


