"""DEV-only calibration for the meta_cortex/v1 instrument.

This module implements:

1. **Frozen normalized-exact scorer** — replaces substring checks with
   NFKC-normalized exact token matching.  The scorer hash covers the
   canonical scorer spec, not Python object repr.

2. **Seed derivation** — domain-separated SHA-256-derived uint63 seeds
   for developmental, evaluation, no_update_repeat, and
   task_cluster_bootstrap domains.

3. **Statistical engine** — nearest-rank empirical P95 equivalence margin,
   paired task effects, deterministic task-cluster confidence intervals,
   and meta-validation-only power analysis.

4. **Calibration campaign** — task-first repeated no-update/meta-validation
   calibration with non-overlapping pairing, joint worst-surface
   repeatability, and one common powered sample size.

Design invariants:
- The task is the independent unit; seed repeats are within-task.
- Common N >= 30 is selected deterministically.
- Formulas and inputs are recorded in evidence artifacts.
- One-step smoke evidence is rejected as calibration input.
- Never accesses sealed test payload.
- ``holdout_accessed`` is always ``false`` in calibration output.
- All ratios/differences are exact ``Fraction``s from correct/total.
- The nearest-rank P95 is non-interpolating: k=ceil(0.95*M), margin=v_(k).
- 95% CI equivalence containment is the conservative TOST-equivalent
  with one-sided alpha 0.025, not the usual 90%-CI/alpha-0.05 TOST.
- The all-pass scientific claim is an intersection-union test; no
  multiplicity correction is added.
"""

