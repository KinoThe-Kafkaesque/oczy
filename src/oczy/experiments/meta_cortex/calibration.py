def task_mean_ci(
    values: list[float],
    *,
    confidence_level: float = 0.95,
) -> dict[str, float]:
    """Compute a two-sided Student-t CI for the mean of *values*.

    The independent n and degrees of freedom are ``len(values)`` and
    ``n-1`` — never probes, seed cells, or repeat runs.

    Returns ``{"n", "mean", "sd", "ci_lower", "ci_upper", "t_critical"}``.
    """
    n = len(values)
    if n < 2:
        if n == 0:
            raise ValueError("Cannot compute CI for empty list")
        return {
            "n": 1,
            "mean": float(values[0]),
            "sd": 0.0,
            "ci_lower": float("nan"),
            "ci_upper": float("nan"),
            "t_critical": float("nan"),
        }

    m = sum(values) / n
    sq_sum = sum((v - m) ** 2 for v in values)
    s = math.sqrt(sq_sum / (n - 1))
    tcrit = t_critical_975(n - 1)
    sem = s / math.sqrt(n)
    half = tcrit * sem

    return {
        "n": n,
        "mean": m,
        "sd": s,
        "ci_lower": m - half,
        "ci_upper": m + half,
        "t_critical": tcrit,
    }


# ---------------------------------------------------------------------------
# Nearest-rank P95
# ---------------------------------------------------------------------------


def nearest_rank_p95(values: list[Fraction]) -> dict[str, Any]:
    """Compute the non-interpolating nearest-rank P95.

    Sorts ascending.  With M = len(values), k = ceil(0.95 * M)
    (one-indexed).  The P95 is v_(k), the k-th smallest value.

    Returns a dict with M, k, the selected value (as num/den), adjacent
    values, and the canonical decimal string.
    """
    if len(values) == 0:
        raise ValueError("Cannot compute P95 of empty list")

    M = len(values)
    k = math.ceil(0.95 * M)
    if k < 1:
        k = 1
    if k > M:
        k = M

    sorted_vals = sorted(values)
    selected = sorted_vals[k - 1]  # one-indexed -> zero-indexed

    # Adjacent values for audit.
    lower_adj = sorted_vals[max(0, k - 2)] if k >= 2 else None
    upper_adj = sorted_vals[min(M - 1, k)] if k < M else None

    margin_str = canonical_decimal_string(
        selected.numerator, selected.denominator
    )
    # Parse the canonical decimal string back to unreduced num/den so that
    # selected_num/selected_den reconstruct the exact decimal representation.
    # All num/den fields use the same decimal-string round-trip to preserve
    # the original decimal place count (Fraction auto-reduces 2/10 → 1/5).
    selected_num, selected_den = _decimal_string_to_num_den(margin_str)

    def _frac_to_num_den(frac: Fraction) -> tuple[int, int]:
        s = canonical_decimal_string(frac.numerator, frac.denominator)
        return _decimal_string_to_num_den(s)

    return {
        "M": M,
        "k": k,
        "selected_num": selected_num,
        "selected_den": selected_den,
        "selected_string": margin_str,
        "lower_adjacent_num": _frac_to_num_den(lower_adj)[0] if lower_adj is not None else None,
        "lower_adjacent_den": _frac_to_num_den(lower_adj)[1] if lower_adj is not None else None,
        "upper_adjacent_num": _frac_to_num_den(upper_adj)[0] if upper_adj is not None else None,
        "upper_adjacent_den": _frac_to_num_den(upper_adj)[1] if upper_adj is not None else None,
        "sorted_values_num": [_frac_to_num_den(v)[0] for v in sorted_vals],
        "sorted_values_den": [_frac_to_num_den(v)[1] for v in sorted_vals],
    }


