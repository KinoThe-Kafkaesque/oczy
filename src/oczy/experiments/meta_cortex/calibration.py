def _compute_joint_variation(
    records: list[NoUpdateRepeatRecord],
) -> list[Fraction]:
    """Compute the joint worst-surface repeatability statistic per pair.

    Pair repeats non-overlapping as (0,1), (2,3), ..., (18,19).
    For pair j define:
        v_tdj = max(|S_td,2j - S_td,2j+1|,
                    |P+_td,2j - P-_td,2j|,
                    |P+_td,2j+1 - P-_td,2j+1|)

    Returns one Fraction per pair.
    """
    if len(records) != 20:
        raise ValueError(
            f"Expected exactly 20 repeat records, got {len(records)}"
        )

    # Sort by repeat_index to ensure correct pairing.
    sorted_records = sorted(records, key=lambda r: r.repeat_index)

    joint_stats: list[Fraction] = []
    for j in range(10):
        r0 = sorted_records[2 * j]
        r1 = sorted_records[2 * j + 1]

        # Component 1: |S_td,2j - S_td,2j+1|
        comp1 = abs(r0.specificity_accuracy - r1.specificity_accuracy)

        # Component 2: |P+_td,2j - P-_td,2j|
        comp2 = abs(r0.primary_post_deletion - r0.primary_pre_deletion)

        # Component 3: |P+_td,2j+1 - P-_td,2j+1|
        comp3 = abs(r1.primary_post_deletion - r1.primary_pre_deletion)

        # Joint max.
        joint = max(comp1, comp2, comp3)
        joint_stats.append(joint)

    return joint_stats


def _compute_component_diagnostics(
    records: list[NoUpdateRepeatRecord],
) -> dict[str, dict[str, Any]]:
    """Compute component distributions and their P95s as diagnostics.

    Returns diagnostics for:
    - specificity_pair_diff: |S_td,2j - S_td,2j+1|
    - pre_post_diff_0: |P+_td,2j - P-_td,2j|
    - pre_post_diff_1: |P+_td,2j+1 - P-_td,2j+1|
    """
    sorted_records = sorted(records, key=lambda r: r.repeat_index)

    spec_diffs: list[Fraction] = []
    pre_post_0: list[Fraction] = []
    pre_post_1: list[Fraction] = []

    for j in range(10):
        r0 = sorted_records[2 * j]
        r1 = sorted_records[2 * j + 1]
        spec_diffs.append(abs(r0.specificity_accuracy - r1.specificity_accuracy))
        pre_post_0.append(abs(r0.primary_post_deletion - r0.primary_pre_deletion))
        pre_post_1.append(abs(r1.primary_post_deletion - r1.primary_pre_deletion))

    def _diag(vals: list[Fraction]) -> dict[str, Any]:
        p95 = nearest_rank_p95(vals)
        return {
            "n": len(vals),
            "p95_num": p95["selected_num"],
            "p95_den": p95["selected_den"],
            "p95_string": p95["selected_string"],
            "values_num": [v.numerator for v in sorted(vals)],
            "values_den": [v.denominator for v in sorted(vals)],
        }

    return {
        "specificity_pair_diff": _diag(spec_diffs),
        "pre_post_diff_even": _diag(pre_post_0),
        "pre_post_diff_odd": _diag(pre_post_1),
    }


