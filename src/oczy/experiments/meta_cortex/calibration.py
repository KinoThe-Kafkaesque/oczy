def compute_endpoint_vector(
    conditions: Mapping[str, TaskConditionRecord],
) -> dict[str, Fraction]:
    """Compute all nine endpoint deltas from matched conditions.

    All contrasts are paired within the same rule, dev seed, and eval seed.
    Fails if a required matched condition is missing or uses a different
    denominator.
    """
    required = (C1, C2, C3, C4, C5, C6)
    for cond in required:
        if cond not in conditions:
            raise ValueError(
                f"Missing required condition '{cond}' for endpoint computation"
            )

    c1 = conditions[C1]
    c3 = conditions[C3]

    # Verify all conditions share the same rule fingerprint.
    rule_fp = c1.rule_fingerprint
    for cond in required:
        if conditions[cond].rule_fingerprint != rule_fp:
            raise ValueError(
                "Endpoint conditions must share the same rule_fingerprint"
            )

    # Verify denominators match for primary accuracy pooling.
    def _primary_total(cr: TaskConditionRecord) -> int:
        return cr.same_rule.total + cr.transfer.total + cr.composition.total

    c3_total = _primary_total(c3)
    for cond in required:
        cr = conditions[cond]
        if cond == C3:
            continue
        # C1, C2, C4, C5, C6 should have the same probe totals.
        if _primary_total(cr) != c3_total:
            raise ValueError(
                f"Condition '{cond}' has different primary denominator "
                f"({_primary_total(cr)}) than C3 ({c3_total})"
            )

    # A_primary for a condition.
    def _a_primary(cr: TaskConditionRecord) -> Fraction:
        return cr.primary_accuracy

    # A_transfer for a condition.
    def _a_transfer(cr: TaskConditionRecord) -> Fraction:
        return cr.transfer.accuracy

    # A_composition for a condition.
    def _a_composition(cr: TaskConditionRecord) -> Fraction:
        return cr.composition.accuracy

    # A_specificity for a condition.
    def _a_specificity(cr: TaskConditionRecord) -> Fraction:
        return cr.specificity_accuracy

    c1_rec = conditions[C1]
    c2_rec = conditions[C2]
    c3_rec = conditions[C3]
    c4_rec = conditions[C4]
    c5_rec = conditions[C5]
    c6_rec = conditions[C6]

    endpoints: dict[str, Fraction] = {}

    # adaptation_delta = A_primary(C3_postdelete) - A_primary(C3_prelearning)
    endpoints["adaptation_delta"] = (
        c3_rec.post_deletion_primary.accuracy
        - c3_rec.pre_learning_primary.accuracy
    )

    # transfer_delta = A_transfer(C3) - A_transfer(C1)
    endpoints["transfer_delta"] = _a_transfer(c3_rec) - _a_transfer(c1_rec)

    # composition_delta = A_composition(C3) - A_composition(C1)
    endpoints["composition_delta"] = _a_composition(c3_rec) - _a_composition(c1_rec)

    # meta_training_delta = A_primary(C3) - A_primary(C2)
    endpoints["meta_training_delta"] = _a_primary(c3_rec) - _a_primary(c2_rec)

    # feedback_semantics_delta = A_primary(C3) - A_primary(C4)
    endpoints["feedback_semantics_delta"] = _a_primary(c3_rec) - _a_primary(c4_rec)

    # causal_state_delta = A_primary(C3) - A_primary(C5)
    endpoints["causal_state_delta"] = _a_primary(c3_rec) - _a_primary(c5_rec)

    # state_addressing_delta = A_primary(C3) - A_primary(C6)
    endpoints["state_addressing_delta"] = _a_primary(c3_rec) - _a_primary(c6_rec)

    # specificity_delta = A_specificity(C3) - A_specificity(C1)
    endpoints["specificity_delta"] = _a_specificity(c3_rec) - _a_specificity(c1_rec)

    # trace_free_survival = A_primary(C3_postdelete) - A_primary(C3_immediately_predelete)
    endpoints["trace_free_survival"] = (
        c3_rec.post_deletion_primary.accuracy
        - c3_rec.immediately_pre_deletion_primary.accuracy
    )

    return endpoints


