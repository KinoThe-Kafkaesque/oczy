def _uint63_from_sha256(label: str) -> int:
    """Derive a uint63 from SHA-256 of a label string."""
    digest = hashlib.sha256(label.encode("utf-8")).digest()
    val = int.from_bytes(digest[:8], "big")
    return val & ((1 << 63) - 1)


def derive_seed_table(
    instrument_id: str = INSTRUMENT_ID,
    instrument_version: str = INSTRUMENT_VERSION,
) -> dict[str, Any]:
    """Derive the versioned seed table.

    Each seed is ``uint63(first_8_bytes(SHA256(
    'oczy/meta-cortex/calibration-seeds/v1|meta_cortex/v1|<domain>|<index>')))``.

    Domains: developmental (indices 0..4), evaluation (indices 0..4),
    no_update_repeat (indices 0..19), task_cluster_bootstrap (index 0).

    Returns a dict with ordered integer vectors and the derivation schema.
    """
    prefix = f"{SEED_DERIVATION_SCHEMA}|{instrument_id}|{instrument_version}"

    developmental = tuple(
        _uint63_from_sha256(f"{prefix}|developmental|{i}") for i in range(5)
    )
    evaluation = tuple(
        _uint63_from_sha256(f"{prefix}|evaluation|{i}") for i in range(5)
    )
    no_update_repeat = tuple(
        _uint63_from_sha256(f"{prefix}|no_update_repeat|{i}") for i in range(20)
    )
    task_cluster_bootstrap = _uint63_from_sha256(f"{prefix}|task_cluster_bootstrap|0")

