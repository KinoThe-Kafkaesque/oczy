# Canonical decimal string
# ---------------------------------------------------------------------------


def canonical_decimal_string(
    numerator: int,
    denominator: int,
    *,
    max_precision: int = 50,
) -> str:
    """Convert an exact Fraction to a canonical decimal string.

    Uses round-half-even at max_precision.  The result is a non-exponent
    decimal string.  Trailing zeros are stripped except for a single
    trailing zero after a decimal point if the value is an integer
    (e.g. ``"0.0"`` not ``"0"``).

    The final evaluation parses and compares this decimal exactly; it does
    not use float tolerance.
    """
    if denominator == 0:
        raise ValueError("denominator must be nonzero")
    if denominator < 0:
        numerator = -numerator
        denominator = -denominator

    # Compute the decimal expansion with round-half-even at max_precision.
    sign = "-" if numerator < 0 else ""
    num_abs = abs(numerator)

    integer_part = num_abs // denominator
    remainder = num_abs % denominator

    # Compute fractional digits with round-half-even.
    digits: list[str] = []
    for _ in range(max_precision):
        remainder *= 10
        digit = remainder // denominator
        digits.append(str(digit))
        remainder = remainder % denominator
        if remainder == 0:
            break

    # Round-half-even at max_precision.
    if len(digits) >= max_precision and remainder != 0:
        # Check the next digit for rounding.
        remainder *= 10
        next_digit = remainder // denominator
        if next_digit > 5 or (next_digit == 5 and int(digits[-1]) % 2 == 1):
            # Round up.
            carry = 1
            new_digits: list[str] = []
            for d in reversed(digits):
                val = int(d) + carry
                if val >= 10:
                    val = 0
                    carry = 1
                else:
                    carry = 0
                new_digits.append(str(val))
            if carry:
                integer_part += 1
            digits = list(reversed(new_digits))

    # Strip trailing zeros.
    while digits and digits[-1] == "0":
        digits.pop()

    if not digits:
        return f"{sign}{integer_part}.0"

    return f"{sign}{integer_part}.{''.join(digits)}"


def _decimal_string_to_num_den(s: str) -> tuple[int, int]:
    """Parse a canonical decimal string to (numerator, denominator).

    ``"0.18"`` → ``(18, 100)``; ``"0.0"`` → ``(0, 1)``; ``"1.5"`` → ``(15, 10)``.
    The result is NOT reduced — it preserves the decimal place count so that
    ``num/den`` reconstructs the exact decimal string.
    """
    s = s.strip()
    if s.startswith("-"):
        sign = -1
        s = s[1:]
    else:
        sign = 1
    if "." not in s:
        return (sign * int(s), 1)
    int_part, frac_part = s.split(".", 1)
    if not frac_part:
        return (sign * int(int_part), 1)
    num = int(int_part + frac_part) if int_part else int(frac_part)
    if sign == -1:
        num = -num
    den = 10 ** len(frac_part)
    if num == 0:
        return (0, 1)
    return (num, den)


